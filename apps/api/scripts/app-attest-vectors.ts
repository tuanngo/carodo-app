/**
 * Writes the App Attest test vectors both repositories check (carodo-ios docs/sync.md "App Attest"):
 *
 *   node apps/api/scripts/app-attest-vectors.ts          # apps/api/test/fixtures/app-attest-vectors.json
 *   node apps/api/scripts/app-attest-vectors.ts --ios    # and the iOS tests' copy, next to this repo
 *
 * The original lives here, with the code that decides which bytes are valid; the iOS repository
 * keeps a copy in its test bundle, so each repository's tests run from its own checkout. A fresh
 * key and fresh signatures each run (ECDSA is randomised), so run it only when a byte format
 * changes, with --ios, then run both sides' tests. The key is a test key and nothing else.
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { assertion, clientData, debugAttestation, generateP256, sha256 } from "../test/support/app-attest.ts";
import { bytesToHex, toBase64 } from "../test/support/encode.ts";

const ORIGINAL = fileURLToPath(new URL("../test/fixtures/app-attest-vectors.json", import.meta.url));
/** The workspace layout: carodo-ios next to carodo-app. */
const IOS_REPO = fileURLToPath(new URL("../../../../carodo-ios/", import.meta.url));
const IOS_COPY = `${IOS_REPO}CarodoTests/Fixtures/app-attest-vectors.json`;

const appId = "TESTTEAM00.app.carodo.ios";
const challenge = "q3JpTzd4b0ZQd2dGaXhJb2xUWkJ3b3RlS2F4c0Z1dEE";
const keys = await generateP256();
const jwk = await crypto.subtle.exportKey("jwk", keys.privateKey);
const privateKey = Uint8Array.from(atob((jwk.d as string).replaceAll("-", "+").replaceAll("_", "/")), (c) =>
  c.charCodeAt(0),
);
const made = await debugAttestation(keys, challenge);

async function request(method: string, pathAndQuery: string, body: string, counter: number) {
  const bodyBytes = new TextEncoder().encode(body);
  const data = await clientData(method, pathAndQuery, bodyBytes);
  const signed = await assertion(keys.privateKey, appId, counter, data);
  return {
    method,
    pathAndQuery,
    body,
    clientData: new TextDecoder().decode(data),
    counter,
    authenticatorData: bytesToHex(signed.authenticatorData),
    nonce: bytesToHex(signed.nonce),
    assertion: toBase64(signed.assertion),
    header: `key=:${toBase64(made.keyId)}:, assertion=:${toBase64(signed.assertion)}:`,
  };
}

const vectors = {
  about:
    'App Attest byte formats (docs/sync.md "App Attest"), generated by carodo-app apps/api/scripts/app-attest-vectors.ts. Test key only. Hex for raw bytes, standard base64 where the wire uses base64.',
  appId,
  rpIdHash: bytesToHex(await sha256(new TextEncoder().encode(appId))),
  challenge,
  clientDataHash: bytesToHex(await sha256(new TextEncoder().encode(challenge))),
  key: {
    privateKey: bytesToHex(privateKey),
    publicKey: bytesToHex(made.publicKey),
    keyId: toBase64(made.keyId),
  },
  debugAttestation: toBase64(made.attestation),
  assertions: [
    await request("POST", "/v1/auth/guest", "", 1),
    await request("PUT", "/v1/drives/0b6f3c5e-6a43-4f7e-9d0e-2f1c8a7b9e10?draft=1", '{"distanceM":12345.6}', 2),
  ],
};

const text = `${JSON.stringify(vectors, null, 2)}\n`;
writeFileSync(ORIGINAL, text);
console.log(`wrote ${ORIGINAL}`);
if (process.argv.includes("--ios")) {
  if (!existsSync(IOS_REPO)) throw new Error(`no carodo-ios at ${IOS_REPO}`);
  mkdirSync(dirname(IOS_COPY), { recursive: true });
  writeFileSync(IOS_COPY, text);
  console.log(`wrote ${IOS_COPY}`);
}
