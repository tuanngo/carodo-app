import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname } from "node:path";
import { fileURLToPath } from "node:url";

const types = { ".jpg": "image/jpeg", ".png": "image/png" };

/** Where the site's videos live: the public R2 bucket `carodo-media` on its custom domain, shared by
 * staging and production (docs/operations/deploy.md). Videos are too heavy for the Worker. */
export const MEDIA_ORIGIN = "https://media.carodo.app";

/** The site's videos (media/*.mp4) by key: their file, their hashed key in R2 and their size. */
export function listVideos() {
  const root = fileURLToPath(new URL("../", import.meta.url));
  return readdirSync(`${root}media`)
    .filter((name) => name.endsWith(".mp4"))
    .sort()
    .map((name) => {
      const file = `${root}media/${name}`;
      const bytes = readFileSync(file);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      const key = name.slice(0, -4);
      const [width, height] = mp4Size(bytes);
      return { key, file, objectKey: `${key}.${hash}.mp4`, width, height };
    });
}

/**
 * The site's images (media/*.jpg: app screens of the synthetic showcase drives; media/*.png: the
 * brand's icons and Open Graph card) as a module the Worker serves from memory: no R2, no Assets
 * binding (P6). Each file's URL carries a hash of its bytes, so it can be cached for good. Trusted
 * build input only.
 */
export function buildMedia() {
  const root = fileURLToPath(new URL("../", import.meta.url));
  const entries = readdirSync(`${root}media`)
    .filter((name) => extname(name) in types)
    .sort()
    .map((name) => {
      const bytes = readFileSync(`${root}media/${name}`);
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 10);
      const ext = extname(name);
      const [w, h] = ext === ".png" ? pngSize(bytes) : jpegSize(bytes);
      const key = name.slice(0, -ext.length);
      const path = `/media/${key}.${hash}${ext}`;
      return { key, path, width: w, height: h, type: types[ext], base64: bytes.toString("base64") };
    });
  const body = entries
    .map(
      (e) =>
        `  ${JSON.stringify(e.key)}: { path: ${JSON.stringify(e.path)}, width: ${e.width}, height: ${e.height}, type: ${JSON.stringify(e.type)}, base64: ${JSON.stringify(e.base64)} },`,
    )
    .join("\n");
  const videos = listVideos()
    .map(
      (v) =>
        `  ${JSON.stringify(v.key)}: { url: ${JSON.stringify(`${MEDIA_ORIGIN}/${v.objectKey}`)}, width: ${v.width}, height: ${v.height} },`,
    )
    .join("\n");
  const module = `// Generated by scripts/build-media.mjs from media/; do not edit.\nexport type SiteImage = { path: string; width: number; height: number; type: string; base64: string };\nexport const siteMedia: Record<string, SiteImage> = {\n${body}\n};\nexport type SiteVideo = { url: string; width: number; height: number };\nexport const siteVideos: Record<string, SiteVideo> = {\n${videos}\n};\n`;
  const target = `${root}src/.generated/media.ts`;
  let previous;
  try {
    previous = readFileSync(target, "utf8");
  } catch {
    /* First build. */
  }
  if (previous !== module) writeFileSync(target, module);
}

/** Width and height of an MP4's first visual track, from its track header box (`tkhd`). */
function mp4Size(bytes) {
  for (let i = bytes.indexOf("tkhd"); i > 0; i = bytes.indexOf("tkhd", i + 4)) {
    const at = i + 4 + (bytes[i + 4] === 1 ? 88 : 76);
    const width = bytes.readUInt32BE(at) >>> 16;
    const height = bytes.readUInt32BE(at + 4) >>> 16;
    if (width > 0 && height > 0) return [width, height];
  }
  throw new Error("not an MP4 with a visual track");
}

/** Width and height from a PNG's IHDR chunk. */
function pngSize(bytes) {
  if (bytes.toString("ascii", 12, 16) !== "IHDR") throw new Error("not a PNG with an IHDR chunk");
  return [bytes.readUInt32BE(16), bytes.readUInt32BE(20)];
}

/** Width and height from a JPEG's start-of-frame marker. */
function jpegSize(bytes) {
  let i = 2;
  while (i < bytes.length) {
    const marker = bytes[i + 1];
    const length = bytes.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xc3) return [bytes.readUInt16BE(i + 7), bytes.readUInt16BE(i + 5)];
    i += 2 + length;
  }
  throw new Error("not a JPEG with a frame header");
}
