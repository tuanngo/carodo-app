import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { buildMedia } from "./build-media.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
mkdirSync(`${root}src/.generated`, { recursive: true });
const result = spawnSync(
  `${root}node_modules/.bin/tailwindcss`,
  ["-i", "src/styles/public.css", "-o", "src/.generated/styles.css", "--minify"],
  { cwd: root, stdio: "inherit" },
);
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
const css = readFileSync(`${root}src/.generated/styles.css`, "utf8");
// Trusted build input only. Never accept user content in this stylesheet.
const module = `// Generated by scripts/build-styles.mjs; do not edit.\nexport const publicStyles = ${JSON.stringify(css)};\n`;
const target = `${root}src/.generated/styles.ts`;
let previous;
try {
  previous = readFileSync(target, "utf8");
} catch {
  /* First build. */
}
if (previous !== module) writeFileSync(target, module);
// The images the pages show, beside the styles: every caller of this script needs both.
buildMedia();
